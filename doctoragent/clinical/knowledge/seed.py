def seed_knowledge(vault_dir: Path, overwrite: bool = False) -> int:
    """Write the built-in knowledge docs into ``vault_dir/临床知识``.

    Returns the number of docs written. Files are only written once unless
    *overwrite* is True (keeps user's later edits intact).
    """
    target = Path(vault_dir) / "临床知识"
    target.mkdir(parents=True, exist_ok=True)
    written = 0
    for topic, md in KNOWLEDGE_DOCS:
        path = target / f"{topic}.md"
        if path.exists() and not overwrite:
            continue
        path.write_text(md, encoding="utf-8")
        written += 1
    return written


def list_knowledge() -> list[dict[str, str]]:
    """Return the built-in knowledge docs (for API/console display)."""
    return [{"topic": t, "content": md} for t, md in KNOWLEDGE_DOCS]
